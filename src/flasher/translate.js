const KEEP = new Set(['SP Blank RT Family', 'USB COMPOSITE DEVICE', 'Stadia Controller', 'Bootloader', 'Stadia', 'Chrome', 'Bluetooth'])
const REPORTED = new Set()

export function reportMissing(text) {
  if (!import.meta.env?.DEV) return
  const core = normalize(text)
  if (!core || KEEP.has(core) || REPORTED.has(core) || !/[A-Za-z]{3}/.test(core) || /^[\w.-]+\.(svg|webp)$/.test(core)) return
  REPORTED.add(core)
  console.warn('[i18n] missing Italian translation for engine text:', core)
}

