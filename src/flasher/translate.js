const PATTERNS = [
  [/^Your controller’s battery is (\d+)%\. It needs to be charged to 10% or more to continue\. Charging from 0–10% can take up to 30 minutes\. Restart the step to check the battery again\.$/, (m) => `La batteria del controller è al ${m[1]}%. Per continuare deve essere carica almeno al 10%. Caricare da 0 a 10% può richiedere fino a 30 minuti. Riavvia il passaggio per controllare di nuovo la batteria.`],
  [/^Unable to flash devices with serial number prefix (\d+)$/, (m) => `Impossibile aggiornare i dispositivi con prefisso del numero di serie ${m[1]}`],
]

export function normalize(text) {
  return text.replace(/ /g, ' ').replace(/\s+/g, ' ').trim()
}

export function translate(text, language) {
  const core = normalize(text)
  if (language !== 'it' || !core) return text
  const hit = IT[core]
  if (hit) return text.replace(core, hit).replace(/^\s+|\s+$/g, (space) => (space ? ' ' : ''))
  for (const [pattern, build] of PATTERNS) {
    const match = core.match(pattern)
    if (match) return build(match)
  }
  reportMissing(core)
  return text
}

export function lookupTemplate(key, language) {
  if (language !== 'it') return null
  return IT[key] || null
}

export function translateAlt(text, language) {
  if (language !== 'it' || !text) return text
  const core = normalize(text)
  for (const [prefix, value] of ALT_IT) if (core.startsWith(prefix)) return value
  return translate(text, language)
}

export function translateLabel(text, language) {
  if (language !== 'it' || !text) return text
  return text.split(', ').map((part) => translate(part, language)).join(', ')
}
